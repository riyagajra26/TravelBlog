
function showMessage(place) {

    if (place === "Jaipur") {

        alert("Explore the Pink City and visit Hawa Mahal and Amber Fort!");

    }

    else if (place === "Kashmir") {

        alert("Enjoy the beautiful valleys, Dal Lake and snow-covered mountains!");

    }

    else if (place === "Kerala") {

        alert("Experience Kerala's beautiful backwaters, Munnar and houseboats!");

    }

}
